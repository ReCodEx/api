<?php

namespace App\Console;

use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use OpenApi\Builder;

/**
 * Command that consumes a temporary file containing endpoint annotations and generates a swagger documentation.
 */
#[AsCommand(
    name: 'swagger:generate',
    description: 'Generate an OpenAPI documentation from the temporary file created by the swagger:annotate command. '
        . 'The temporary file is deleted afterwards.'
)]
class SwaggerGenerator extends Command
{
    private static string $annotationsFile = __DIR__ . '/../V1Module/presenters/_autogenerated_annotations_temp.php';

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        // check if file exists
        if (!file_exists(self::$annotationsFile)) {
            $output->writeln("Error in SwaggerGenerator: Temp annotation file not found.");
            return Command::FAILURE;
        }

        $builder = new Builder();
        $builder->addSource(self::$annotationsFile);
        $result = $builder->build();
        $output->writeln($result->toYaml());

        // $generator = new Generator();
        // $openapi = $generator->generate([self::$annotationsFile]);

        //$output->writeln($openapi->toYaml());

        // delete the temp file
        //        unlink(self::$annotationsFile);

        return Command::SUCCESS;
    }
}
